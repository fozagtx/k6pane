"""Generate k6 scripts from a structured test spec.

The spec is embedded into the script as JSON, so user-supplied URLs, headers
and bodies can never break out into executable JavaScript.
"""

from __future__ import annotations

import json
import re
from typing import Any, Dict, List

from .durations import format_seconds, parse_duration
from .redact import check_host_is_literal, find_refs

PROFILES = ("smoke", "load", "stress", "spike", "soak", "constant")
METHODS = {"GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"}
DEFAULT_THRESHOLDS = {
    "http_req_duration": ["p(95)<500"],
    "http_req_failed": ["rate<0.01"],
}

_TEMPLATE = """\
// Generated by k6pane. Edit freely; re-run with k6pane_run(script_path=...).
// Secret values are never stored here: ${secret.NAME} placeholders are filled
// at run time from k6's secret source, which also redacts them from logs.
import http from 'k6/http';
import secrets from 'k6/secrets';
import { check, sleep } from 'k6';

const CONFIG = __CONFIG__;

export const options = CONFIG.options;

const REF = /\\$\\{(secret|var|row)\\.([A-Za-z0-9_]+)\\}/g;

function fill(value, ctx) {
  if (typeof value === 'string') {
    return value.replace(REF, (m, ns, key) => {
      const src = ctx[ns] || {};
      return Object.prototype.hasOwnProperty.call(src, key) ? String(src[key]) : m;
    });
  }
  if (Array.isArray(value)) return value.map((v) => fill(v, ctx));
  if (value !== null && typeof value === 'object') {
    const out = {};
    for (const k of Object.keys(value)) out[k] = fill(value[k], ctx);
    return out;
  }
  return value;
}

let SECRETS = null;
async function loadSecrets() {
  if (SECRETS !== null) return SECRETS;
  const out = {};
  for (const name of CONFIG.secret_names) out[name] = await secrets.get(name);
  SECRETS = out;
  return out;
}

export default async function () {
  const ctx = { secret: await loadSecrets(), var: {}, row: {} };
  for (const req of CONFIG.requests) {
    const headers = fill(Object.assign({}, req.headers || {}), ctx);
    let body = null;
    if (req.json !== undefined && req.json !== null) {
      body = JSON.stringify(fill(req.json, ctx));
      const hasType = Object.keys(headers).some((h) => h.toLowerCase() === 'content-type');
      if (!hasType) headers['Content-Type'] = 'application/json';
    } else if (req.body !== undefined && req.body !== null) {
      body = fill(req.body, ctx);
    }
    const res = http.request(req.method, fill(req.url, ctx), body, {
      headers: headers,
      tags: { name: req.name },
      timeout: CONFIG.request_timeout,
      responseCallback: http.expectedStatuses(...req.expect_status),
    });
    check(res, {
      [req.name + ' status ' + req.expect_status.join('|')]: (r) => req.expect_status.indexOf(r.status) !== -1,
    });
    if (req.sleep > 0) sleep(req.sleep);
  }
  if (CONFIG.think_time > 0) sleep(CONFIG.think_time);
}
"""


def _slug(text: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_.-]+", "_", text).strip("_")[:60] or "req"


def normalize_requests(raw: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    if not raw:
        raise ValueError("At least one request is required (pass `url` or `requests`).")
    out: List[Dict[str, Any]] = []
    seen = set()
    for i, r in enumerate(raw):
        if not isinstance(r, dict) or not r.get("url"):
            raise ValueError(f"requests[{i}] needs a `url`.")
        url = str(r["url"]).strip()
        if not re.match(r"^https?://", url, re.IGNORECASE):
            raise ValueError(f"requests[{i}].url must start with http:// or https:// (got {url!r}).")
        check_host_is_literal(url)
        method = str(r.get("method", "GET")).upper()
        if method not in METHODS:
            raise ValueError(f"requests[{i}].method {method!r} not supported ({', '.join(sorted(METHODS))}).")
        expect = r.get("expect_status", 200)
        expect = expect if isinstance(expect, list) else [expect]
        try:
            expect = [int(s) for s in expect]
        except (TypeError, ValueError):
            raise ValueError(f"requests[{i}].expect_status must be an int or list of ints.") from None
        name = _slug(str(r.get("name") or f"{method} {url.split('://', 1)[1].split('?')[0]}"))
        base, n = name, 2
        while name in seen:
            name, n = f"{base}_{n}", n + 1
        seen.add(name)
        headers = r.get("headers") or {}
        if not isinstance(headers, dict):
            raise ValueError(f"requests[{i}].headers must be an object.")
        out.append({
            "name": name,
            "method": method,
            "url": url,
            "headers": {str(k): str(v) for k, v in headers.items()},
            "json": r.get("json"),
            "body": r.get("body"),
            "expect_status": expect,
            "sleep": float(r.get("sleep", 0) or 0),
        })
    return out


def build_stages(profile: str, vus: int, duration_s: float) -> List[Dict[str, Any]]:
    """Stage plan for ramping profiles. `vus` is the peak."""
    d = duration_s
    base = max(1, vus // 10)
    plans = {
        "load": [(0.2, vus), (0.7, vus), (0.1, 0)],
        "soak": [(0.05, vus), (0.9, vus), (0.05, 0)],
        "stress": [
            (0.1, max(1, vus // 4)), (0.1, max(1, vus // 4)),
            (0.1, max(1, vus // 2)), (0.1, max(1, vus // 2)),
            (0.1, max(1, (vus * 3) // 4)), (0.1, max(1, (vus * 3) // 4)),
            (0.1, vus), (0.2, vus), (0.1, 0),
        ],
        "spike": [(0.1, base), (0.1, base), (0.05, vus), (0.25, vus), (0.05, base), (0.35, base), (0.1, 0)],
    }
    return [{"duration": format_seconds(frac * d), "target": target} for frac, target in plans[profile]]


def stages_duration(stages: List[Dict[str, Any]]) -> float:
    return sum(parse_duration(s["duration"]) for s in stages)


def build_options(spec: Dict[str, Any]) -> Dict[str, Any]:
    """Build k6 `options` and return them plus the planned seconds and peak VUs."""
    profile = spec["profile"]
    vus = spec["vus"]
    duration_s = spec["duration_s"]
    options: Dict[str, Any] = {"discardResponseBodies": True}

    if spec.get("rate"):
        rate = int(spec["rate"])
        max_vus = spec.get("max_vus") or max(vus, 1) * 2
        options["scenarios"] = {
            "arrival_rate": {
                "executor": "constant-arrival-rate",
                "rate": rate,
                "timeUnit": "1s",
                "duration": format_seconds(duration_s),
                "preAllocatedVUs": max(1, vus),
                "maxVUs": max_vus,
            }
        }
        planned, peak = duration_s, max_vus
    elif spec.get("stages"):
        stages = [{"duration": format_seconds(parse_duration(s["duration"])), "target": int(s["target"])}
                  for s in spec["stages"]]
        options["stages"] = stages
        planned, peak = stages_duration(stages), max(s["target"] for s in stages)
    elif profile in ("smoke", "constant"):
        n = 1 if profile == "smoke" else vus
        options["vus"] = n
        options["duration"] = format_seconds(duration_s)
        planned, peak = duration_s, n
    else:
        stages = build_stages(profile, vus, duration_s)
        options["stages"] = stages
        planned, peak = stages_duration(stages), vus

    thresholds = dict(spec.get("thresholds") or {})
    if not thresholds:
        thresholds = {k: list(v) for k, v in DEFAULT_THRESHOLDS.items()}
        if spec.get("p95_ms") is not None:
            thresholds["http_req_duration"] = [f"p(95)<{spec['p95_ms']}"]
        if spec.get("p99_ms") is not None:
            thresholds["http_req_duration"].append(f"p(99)<{spec['p99_ms']}")
        if spec.get("max_error_rate") is not None:
            thresholds["http_req_failed"] = [f"rate<{spec['max_error_rate']}"]
    # Always-true thresholds force k6 to export per-endpoint sub-metrics.
    for req in spec["requests"]:
        thresholds.setdefault(f"http_req_duration{{name:{req['name']}}}", ["max>=0"])
        thresholds.setdefault(f"http_req_failed{{name:{req['name']}}}", ["rate>=0"])
    options["thresholds"] = thresholds
    return {"options": options, "planned_seconds": planned, "peak_vus": peak}


def render_script(spec: Dict[str, Any], options: Dict[str, Any]) -> str:
    config = {
        "options": options,
        "requests": spec["requests"],
        "think_time": float(spec.get("think_time", 1)),
        "request_timeout": spec.get("request_timeout", "30s"),
        "secret_names": find_refs(spec["requests"], "secret"),
    }
    payload = json.dumps(config, indent=2).replace("</", "<\\/")
    return _TEMPLATE.replace("__CONFIG__", payload)
